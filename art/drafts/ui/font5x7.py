W, H, ADVANCE = 5, 7, 6


def width(text):
    return len(text) * ADVANCE - 1


def draw(img, text, x, y, color, shadow=None):
    if shadow:
        draw(img, text, x + 1, y + 1, shadow)
    for i, ch in enumerate(text):
        rows = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or GLYPHS["?"]
        for r, row in enumerate(rows):
            for c, cell in enumerate(row):
                if cell == "#":
                    img.putpixel((x + i * ADVANCE + c, y + r), color)
